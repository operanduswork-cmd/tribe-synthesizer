// Copies the hosted page schemas from strategist/hosted_schema (the source of truth) into
// web/contracts/hosted_schema (the deployed app only sees web/), and writes TypeScript types
// for them to lib/hosted.gen.ts. Run `npm run gen:hosted` after a schema change;
// `npm run gen:hosted -- --check` fails when either output is stale (strategist/test_web_copy.py
// checks the copies too).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.resolve(WEB, "..", "strategist", "hosted_schema");
const DEST = path.join(WEB, "contracts", "hosted_schema");
const OUT = path.join(WEB, "lib", "hosted.gen.ts");
const KINDS = ["board", "reel", "patterns", "lab", "tribe", "brain", "meta", "spend"];
const check = process.argv.includes("--check");

const pascal = (s) => s.replace(/(^|[_-])([a-z])/g, (_, __, c) => c.toUpperCase());
const lit = (v) => JSON.stringify(v);
const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function resolve(root, ref) {
  if (!ref.startsWith("#/")) throw new Error(`only local $ref is supported: ${ref}`);
  return ref.slice(2).split("/").reduce((node, part) => node[part.replace(/~1/g, "/").replace(/~0/g, "~")], root);
}

// One JSON Schema node to a TypeScript type. Constraints (pattern, lengths, not) are left to the
// runtime check in lib/contract.ts; this is only the shape.
function ts(node, root, indent) {
  if (node === true || node === undefined) return "unknown";
  if (node === false) return "never";
  if (node.$ref) return ts(resolve(root, node.$ref), root, indent);
  const choices = node.anyOf || node.oneOf;
  if (choices) return union(choices.map((c) => ts(c, root, indent)));
  if ("const" in node) return lit(node.const);
  if (node.enum) return union(node.enum.map(lit));
  const types = Array.isArray(node.type) ? node.type : node.type ? [node.type] : [];
  if (!types.length) return "unknown";
  return union(types.map((t) => one(t, node, root, indent)));
}

function one(t, node, root, indent) {
  switch (t) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return arrayType(node, root, indent);
    case "object":
      return objectType(node, root, indent);
    default:
      throw new Error(`unknown type ${t}`);
  }
}

function arrayType(node, root, indent) {
  const prefix = node.prefixItems || [];
  if (!prefix.length) return `Array<${ts(node.items, root, indent)}>`;
  const min = node.minItems || 0;
  const parts = prefix.map((p, i) => ts(p, root, indent) + (i >= min ? "?" : ""));
  if (node.items !== false) parts.push(`...Array<${ts(node.items, root, indent)}>`);
  return `[${parts.join(", ")}]`;
}

function objectType(node, root, indent) {
  const props = node.properties || {};
  const req = new Set(node.required || []);
  const pad = "  ".repeat(indent + 1);
  const lines = Object.entries(props).map(([k, v]) => {
    const layer = v && v["x-layer"] ? `${pad}/** layer: ${v["x-layer"]} */\n` : "";
    const key = IDENT.test(k) ? k : lit(k);
    return `${layer}${pad}${key}${req.has(k) ? "" : "?"}: ${ts(v, root, indent + 1)};`;
  });
  const extra = node.additionalProperties;
  if (extra && extra !== true) lines.push(`${pad}[key: string]: ${ts(extra, root, indent + 1)};`);
  if (!lines.length) return extra === false ? "Record<string, never>" : "Record<string, unknown>";
  return `{\n${lines.join("\n")}\n${"  ".repeat(indent)}}`;
}

function union(parts) {
  const seen = [...new Set(parts)];
  return seen.length === 1 ? seen[0] : seen.map((p) => (p.includes("\n") ? `(${p})` : p)).join(" | ");
}

const header = `// GENERATED by scripts/gen-hosted.mjs from strategist/hosted_schema. Do not edit by hand.
// Shapes only: every page is checked at runtime against the same schema (lib/contract.ts).
// A property marked "layer" is shown on the site and carries that data-layer.

`;
let out = header;
const copies = [];
for (const kind of KINDS) {
  const raw = fs.readFileSync(path.join(SRC, `${kind}.schema.json`), "utf8");
  const schema = JSON.parse(raw);
  copies.push([path.join(DEST, `${kind}.schema.json`), raw]);
  out += `/** ${schema.title}. Key: ${schema["x-key"]} */\nexport type ${pascal(kind)}Page = ${ts(schema, schema, 0)};\n\n`;
}
out += `export type PageByKind = {\n${KINDS.map((k) => `  ${k}: ${pascal(k)}Page;`).join("\n")}\n};\n\n`;
out += `export type PageKind = keyof PageByKind;\n\nexport const PAGE_KINDS = ${lit(KINDS)} as const;\n`;

const targets = [...copies, [OUT, out]];
const stale = targets.filter(([file, text]) => !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text);
if (check) {
  if (stale.length) {
    console.error(`stale: ${stale.map(([f]) => path.relative(WEB, f)).join(", ")}. Run npm run gen:hosted`);
    process.exit(1);
  }
  console.log("hosted schemas and types are up to date");
} else {
  fs.mkdirSync(DEST, { recursive: true });
  for (const [file, text] of stale) fs.writeFileSync(file, text);
  console.log(`wrote ${stale.length} file(s)`);
}
